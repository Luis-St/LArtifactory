package net.luis.artifactory.handler.format;

import net.luis.artifactory.util.Versions;
import org.jspecify.annotations.NonNull;
import org.jspecify.annotations.Nullable;
import org.w3c.dom.*;

import javax.xml.XMLConstants;
import javax.xml.parsers.DocumentBuilderFactory;
import java.io.ByteArrayInputStream;
import java.nio.charset.StandardCharsets;
import java.util.*;

import static net.luis.artifactory.http.Requests.escapeXml;

/**
 * Artifact and group level {@code maven-metadata.xml}: the versions of an artifact and the plugins of a group.<br>
 * Snapshot level metadata is not modeled, it is generated by the {@link MavenHandler} and taken as a whole when merging.<br>
 *
 * @param groupId The group id, null for pure group level metadata
 * @param artifactId The artifact id, null for pure group level metadata
 * @param latest The newest version including snapshots
 * @param release The newest version without snapshots
 * @param versions All versions, sorted from oldest to newest
 * @param lastUpdated The time of the last change as {@code yyyyMMddHHmmss}
 * @param plugins The plugins of the group with their prefix
 */
record MavenMetadata(
	@Nullable String groupId,
	@Nullable String artifactId,
	@Nullable String latest,
	@Nullable String release,
	@NonNull List<String> versions,
	@Nullable String lastUpdated,
	@NonNull List<Plugin> plugins
) {

	/**
	 * Versions that compare equal (1.0 and 1.0.0) are both listed, they are distinct directories.<br>
	 */
	private static final Comparator<String> ORDER = Versions.MAVEN.thenComparing(Comparator.naturalOrder());

	MavenMetadata {
		versions = List.copyOf(versions);
		plugins = List.copyOf(plugins);
	}

	@NonNull
	static MavenMetadata ofVersions(@NonNull String groupId, @NonNull String artifactId, @NonNull Collection<String> versions, @NonNull String lastUpdated) {
		TreeSet<String> sorted = new TreeSet<>(ORDER);
		sorted.addAll(versions);
		String release = sorted.descendingSet().stream().filter(version -> !version.endsWith("-SNAPSHOT")).findFirst().orElse(null);
		return new MavenMetadata(groupId, artifactId, sorted.isEmpty() ? null : sorted.last(), release, new ArrayList<>(sorted), lastUpdated, List.of());
	}

	/**
	 * Parses xml without doctype and external entities.<br>
	 */
	@NonNull
	static Document parse(byte @NonNull [] data) throws Exception {
		DocumentBuilderFactory factory = DocumentBuilderFactory.newInstance();
		factory.setFeature(XMLConstants.FEATURE_SECURE_PROCESSING, true);
		factory.setFeature("http://apache.org/xml/features/disallow-doctype-decl", true);
		factory.setExpandEntityReferences(false);
		return factory.newDocumentBuilder().parse(new ByteArrayInputStream(data));
	}

	@Nullable
	static Element child(@Nullable Element parent, @NonNull String name) {
		if (parent == null) {
			return null;
		}
		NodeList nodes = parent.getChildNodes();
		for (int i = 0; i < nodes.getLength(); i++) {
			if (nodes.item(i) instanceof Element element && name.equals(element.getTagName())) {
				return element;
			}
		}
		return null;
	}

	@NonNull
	private static List<Element> children(@Nullable Element parent, @NonNull String name) {
		List<Element> result = new ArrayList<>();
		if (parent != null) {
			NodeList nodes = parent.getChildNodes();
			for (int i = 0; i < nodes.getLength(); i++) {
				if (nodes.item(i) instanceof Element element && name.equals(element.getTagName())) {
					result.add(element);
				}
			}
		}
		return result;
	}

	@Nullable
	static String childText(@Nullable Element parent, @NonNull String name) {
		Element element = child(parent, name);
		if (element == null) {
			return null;
		}
		String text = element.getTextContent().strip();
		return text.isEmpty() ? null : text;
	}

	/**
	 * Merges the metadata files of several repositories.<br>
	 * <p>
	 *     Artifact and group level files are combined: the version lists and plugin lists are united, {@code latest}
	 *     and {@code release} are the newest of all files. Snapshot level files can not be combined, their build numbers
	 *     are local to each repository, so the most recently updated file is taken. Files that are not valid xml are ignored.
	 * </p>
	 *
	 * @return The merged metadata, null if no file was given
	 */
	@Nullable
	static String merge(@NonNull List<String> documents) {
		if (documents.size() <= 1) {
			return documents.isEmpty() ? null : documents.getFirst();
		}
		Map<String, Element> roots = new LinkedHashMap<>();
		for (String document : documents) {
			try {
				roots.put(document, parse(document.getBytes(StandardCharsets.UTF_8)).getDocumentElement());
			} catch (Exception ignored) {}
		}
		if (roots.isEmpty()) {
			return documents.getFirst();
		}

		boolean snapshot = roots.values().stream().anyMatch(root -> child(child(root, "versioning"), "snapshot") != null);
		if (snapshot) {
			return roots.entrySet().stream()
				.max(Comparator.comparing(entry -> Objects.requireNonNullElse(childText(child(entry.getValue(), "versioning"), "lastUpdated"), "")))
				.map(Map.Entry::getKey)
				.orElseThrow();
		}

		String groupId = null;
		String artifactId = null;
		TreeSet<String> versions = new TreeSet<>(ORDER);
		TreeSet<String> latest = new TreeSet<>(ORDER);
		TreeSet<String> releases = new TreeSet<>(ORDER);
		String lastUpdated = null;
		Map<String, Plugin> plugins = new LinkedHashMap<>();
		for (Element root : roots.values()) {
			groupId = groupId == null ? childText(root, "groupId") : groupId;
			artifactId = artifactId == null ? childText(root, "artifactId") : artifactId;
			Element versioning = child(root, "versioning");
			for (Element version : children(child(versioning, "versions"), "version")) {
				String text = version.getTextContent().strip();
				if (!text.isEmpty()) {
					versions.add(text);
				}
			}
			Optional.ofNullable(childText(versioning, "latest")).ifPresent(latest::add);
			Optional.ofNullable(childText(versioning, "release")).ifPresent(releases::add);
			String updated = childText(versioning, "lastUpdated");
			if (updated != null && (lastUpdated == null || updated.compareTo(lastUpdated) > 0)) {
				lastUpdated = updated;
			}
			for (Element plugin : children(child(root, "plugins"), "plugin")) {
				String prefix = childText(plugin, "prefix");
				String pluginArtifact = childText(plugin, "artifactId");
				if (prefix != null && pluginArtifact != null) {
					plugins.putIfAbsent(prefix, new Plugin(Objects.requireNonNullElse(childText(plugin, "name"), pluginArtifact), prefix, pluginArtifact));
				}
			}
		}
		latest.addAll(versions);
		if (releases.isEmpty()) {
			versions.stream().filter(version -> !version.endsWith("-SNAPSHOT")).forEach(releases::add);
		}
		return new MavenMetadata(groupId, artifactId, latest.isEmpty() ? null : latest.last(), releases.isEmpty() ? null : releases.last(), new ArrayList<>(versions), lastUpdated, new ArrayList<>(plugins.values())).toXml();
	}

	@NonNull
	MavenMetadata withPlugins(@NonNull List<Plugin> plugins) {
		return new MavenMetadata(this.groupId, this.artifactId, this.latest, this.release, this.versions, this.lastUpdated, plugins);
	}

	@NonNull
	String toXml() {
		StringBuilder xml = new StringBuilder();
		xml.append("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<metadata>\n");
		if (this.groupId != null) {
			xml.append("  <groupId>").append(escapeXml(this.groupId)).append("</groupId>\n");
		}
		if (this.artifactId != null) {
			xml.append("  <artifactId>").append(escapeXml(this.artifactId)).append("</artifactId>\n");
		}
		if (!this.versions.isEmpty() || this.latest != null) {
			xml.append("  <versioning>\n");
			if (this.latest != null) {
				xml.append("    <latest>").append(escapeXml(this.latest)).append("</latest>\n");
			}
			if (this.release != null) {
				xml.append("    <release>").append(escapeXml(this.release)).append("</release>\n");
			}
			xml.append("    <versions>\n");
			for (String version : this.versions) {
				xml.append("      <version>").append(escapeXml(version)).append("</version>\n");
			}
			xml.append("    </versions>\n");
			if (this.lastUpdated != null) {
				xml.append("    <lastUpdated>").append(escapeXml(this.lastUpdated)).append("</lastUpdated>\n");
			}
			xml.append("  </versioning>\n");
		}
		if (!this.plugins.isEmpty()) {
			xml.append("  <plugins>\n");
			for (Plugin plugin : this.plugins) {
				xml.append("    <plugin>\n");
				xml.append("      <name>").append(escapeXml(plugin.name())).append("</name>\n");
				xml.append("      <prefix>").append(escapeXml(plugin.prefix())).append("</prefix>\n");
				xml.append("      <artifactId>").append(escapeXml(plugin.artifactId())).append("</artifactId>\n");
				xml.append("    </plugin>\n");
			}
			xml.append("  </plugins>\n");
		}
		xml.append("</metadata>\n");
		return xml.toString();
	}

	/**
	 * A Maven plugin of a group, {@code mvn prefix:goal} is resolved to the plugin with the prefix.<br>
	 */
	record Plugin(@NonNull String name, @NonNull String prefix, @NonNull String artifactId) {}
}
