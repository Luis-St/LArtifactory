/**
 * Maven 2 layout repository used by Maven and Gradle.<br>
 * <p>
 *     {@code maven-metadata.xml} files are always generated by the server from the stored artifacts,
 *     uploaded metadata files are accepted but ignored. Checksums ({@code .sha1}, {@code .md5}, {@code .sha256}, {@code .sha512})
 *     are computed on upload, uploaded checksum files are verified against the stored artifact.
 * </p>
 */
public class MavenHandler extends PathRepositoryHandler {
	
	private static final String METADATA = "maven-metadata.xml";
	private static final DateTimeFormatter LAST_UPDATED = DateTimeFormatter.ofPattern("yyyyMMddHHmmss").withZone(ZoneOffset.UTC);
	private static final int MAX_REMOTE_METADATA_SIZE = 4 * 1024 * 1024;
	private static final String PLUGIN_DESCRIPTOR = "META-INF/maven/plugin.xml";
	private static final Pattern SNAPSHOT_FILE = Pattern.compile("^(\\d{8}\\.\\d{6})-(\\d+)(?:-([^.]+))?\\.(.+)$");
	
	public MavenHandler(@NonNull Services services) {
		super(services);
	}
	
	@Nullable
	public static Coordinates parseCoordinates(@NonNull String path) {
		String[] segments = path.split("/");
		if (segments.length < 4) {
			return null;
		}
		String fileName = segments[segments.length - 1];
		String version = segments[segments.length - 2];
		String artifactId = segments[segments.length - 3];
		String groupId = String.join(".", Arrays.copyOfRange(segments, 0, segments.length - 3));
		
		boolean matches = fileName.startsWith(artifactId + "-" + version);
		if (!matches && version.endsWith("-SNAPSHOT")) {
			String base = version.substring(0, version.length() - "-SNAPSHOT".length());
			matches = fileName.startsWith(artifactId + "-" + base + "-");
		}
		return matches ? new Coordinates(groupId, artifactId, version, fileName) : null;
	}
	
	@Override
	@NonNull
	public RepositoryType type() {
		return RepositoryType.MAVEN;
	}
	
	@Override
	protected boolean checksumSidecars() {
		return true;
	}
	
	/**
	 * Metadata, its checksums and snapshots change upstream, release files are immutable.<br>
	 */
	@Override
	protected boolean isVolatile(@NonNull String path) {
		String base = checksumExtension(path) == null ? path : stripExtension(path);
		return fileName(base).equals(METADATA) || this.isMutable(base);
	}
	
	@Override
	protected boolean serveComputed(@NonNull Context ctx, @NonNull RepositoryEntity repository, @NonNull String path) throws Exception {
		String checksum = checksumExtension(path);
		String metadataPath = checksum == null ? path : stripExtension(path);
		if (fileName(metadataPath).equals(METADATA)) {
			String xml = this.generateMetadata(repository, metadataPath);
			if (xml == null) {
				return false;
			}
			serveGenerated(ctx, path, xml, "application/xml");
			return true;
		}
		
		FileEntity resolved = this.resolveNonUniqueSnapshot(repository, metadataPath);
		if (resolved != null) {
			if (checksum != null) {
				text(ctx, 200, digest(resolved, checksum));
			} else {
				this.services.artifacts().serve(ctx, resolved);
			}
			return true;
		}
		return false;
	}
	
	/**
	 * Merges the metadata of all members, so a virtual repository lists the versions of every member and not only those of the first.<br>
	 * Local members contribute their generated metadata, remote members the metadata of their upstream.<br>
	 */
	@Override
	protected boolean serveMerged(@NonNull Context ctx, @NonNull RepositoryEntity repository, @NonNull List<RepositoryEntity> members, @NonNull String path) throws Exception {
		String metadataPath = checksumExtension(path) == null ? path : stripExtension(path);
		if (!fileName(metadataPath).equals(METADATA)) {
			return false;
		}
		List<String> documents = new ArrayList<>();
		for (RepositoryEntity member : members) {
			String xml;
			if (this.services.repositories().classOf(member.name()) == net.luis.artifactory.repository.RepositoryClass.LOCAL) {
				xml = this.generateMetadata(member, metadataPath);
			} else {
				byte[] data = this.readRemote(member, metadataPath, MAX_REMOTE_METADATA_SIZE);
				xml = data == null ? null : new String(data, StandardCharsets.UTF_8);
			}
			if (xml != null) {
				documents.add(xml);
			}
		}
		String merged = MavenMetadata.merge(documents);
		if (merged == null) {
			return false;
		}
		serveGenerated(ctx, path, merged, "application/xml");
		return true;
	}
	
	@Override
	protected boolean consumeComputedUpload(@NonNull Context ctx, @NonNull RepositoryEntity repository, @NonNull String path) throws Exception {
		String metadataPath = checksumExtension(path) == null ? path : stripExtension(path);
		if (!fileName(metadataPath).equals(METADATA)) {
			return false;
		}
		try (InputStream input = ctx.bodyInputStream()) {
			input.transferTo(java.io.OutputStream.nullOutputStream());
		}
		ctx.status(201);
		return true;
	}
	
	@Nullable
	private String generateMetadata(@NonNull RepositoryEntity repository, @NonNull String metadataPath) throws Exception {
		int slash = metadataPath.lastIndexOf('/');
		if (slash < 0) {
			return null;
		}
		String directory = metadataPath.substring(0, slash);
		String[] segments = directory.split("/");
		
		if (segments.length >= 3 && segments[segments.length - 1].endsWith("-SNAPSHOT")) {
			String snapshot = this.generateSnapshotMetadata(repository, directory, segments);
			if (snapshot != null) {
				return snapshot;
			}
		}
		// A directory can be an artifact and a group (with plugins) at the same time, both parts go into one file
		MavenMetadata versions = segments.length >= 2 ? this.generateVersionsMetadata(repository, segments) : null;
		List<MavenMetadata.Plugin> plugins = this.generatePlugins(repository, String.join(".", segments));
		if (versions == null && plugins.isEmpty()) {
			return null;
		}
		if (versions == null) {
			versions = new MavenMetadata(null, null, null, null, List.of(), null, plugins);
		} else if (!plugins.isEmpty()) {
			versions = versions.withPlugins(plugins);
		}
		return versions.toXml();
	}
	
	/**
	 * Lists the Maven plugins of a group with their prefix, read from the plugin descriptor of the newest version of each plugin.<br>
	 */
	@NonNull
	private List<MavenMetadata.Plugin> generatePlugins(@NonNull RepositoryEntity repository, @NonNull String groupId) throws Exception {
		List<MavenMetadata.Plugin> plugins = new ArrayList<>();
		for (String packageName : this.services.packages().packageNames(repository.name())) {
			int colon = packageName.lastIndexOf(':');
			if (colon < 0 || !packageName.substring(0, colon).equals(groupId)) {
				continue;
			}
			this.services.artifacts().listByPackage(repository.name(), packageName).stream()
				.filter(file -> file.metadata() != null && file.version() != null)
				.filter(file -> Json.text(Json.parseObject(file.metadata()), "goalPrefix") != null)
				.max(Comparator.comparing(FileEntity::version, Versions.MAVEN))
				.ifPresent(file -> {
					ObjectNode metadata = Json.parseObject(file.metadata());
					String artifactId = packageName.substring(colon + 1);
					plugins.add(new MavenMetadata.Plugin(Json.text(metadata, "pluginName", artifactId), Objects.requireNonNull(Json.text(metadata, "goalPrefix")), artifactId));
				});
		}
		return plugins;
	}
	
	@Nullable
	private MavenMetadata generateVersionsMetadata(@NonNull RepositoryEntity repository, String @NonNull [] segments) throws Exception {
		String artifactId = segments[segments.length - 1];
		String groupId = String.join(".", Arrays.copyOf(segments, segments.length - 1));
		List<FileEntity> files = this.services.artifacts().listByPackage(repository.name(), groupId + ":" + artifactId);
		if (files.isEmpty()) {
			return null;
		}
		
		List<String> versions = new ArrayList<>();
		Instant lastUpdated = Instant.EPOCH;
		for (FileEntity file : files) {
			if (file.version() != null) {
				versions.add(file.version());
			}
			if (file.createdAt().isAfter(lastUpdated)) {
				lastUpdated = file.createdAt();
			}
		}
		return MavenMetadata.ofVersions(groupId, artifactId, versions, LAST_UPDATED.format(lastUpdated));
	}
	
	@NonNull
	private List<SnapshotFile> snapshotFiles(@NonNull RepositoryEntity repository, @NonNull String directory, @NonNull String artifactId, @NonNull String baseVersion) throws Exception {
		List<SnapshotFile> result = new ArrayList<>();
		String prefix = artifactId + "-" + baseVersion + "-";
		for (FileEntity file : this.services.artifacts().list(repository.name(), directory + "/")) {
			String name = file.path().substring(directory.length() + 1);
			if (name.contains("/") || !name.startsWith(prefix) || checksumExtension(name) != null) {
				continue;
			}
			Matcher matcher = SNAPSHOT_FILE.matcher(name.substring(prefix.length()));
			if (matcher.matches()) {
				result.add(new SnapshotFile(matcher.group(1), Integer.parseInt(matcher.group(2)), matcher.group(3), matcher.group(4), file));
			}
		}
		return result;
	}
	
	@Nullable
	private String generateSnapshotMetadata(@NonNull RepositoryEntity repository, @NonNull String directory, String @NonNull [] segments) throws Exception {
		String version = segments[segments.length - 1];
		String artifactId = segments[segments.length - 2];
		String groupId = String.join(".", Arrays.copyOf(segments, segments.length - 2));
		String baseVersion = version.substring(0, version.length() - "-SNAPSHOT".length());
		
		List<FileEntity> all = this.services.artifacts().list(repository.name(), directory + "/");
		if (all.isEmpty()) {
			return null;
		}
		Instant lastUpdated = all.stream().map(FileEntity::createdAt).max(Comparator.naturalOrder()).orElse(Instant.now());
		List<SnapshotFile> files = this.snapshotFiles(repository, directory, artifactId, baseVersion);
		
		StringBuilder xml = new StringBuilder();
		xml.append("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<metadata modelVersion=\"1.1.0\">\n");
		xml.append("  <groupId>").append(escapeXml(groupId)).append("</groupId>\n");
		xml.append("  <artifactId>").append(escapeXml(artifactId)).append("</artifactId>\n");
		xml.append("  <version>").append(escapeXml(version)).append("</version>\n");
		xml.append("  <versioning>\n");
		
		if (files.isEmpty()) {
			xml.append("    <snapshot>\n      <localCopy>true</localCopy>\n    </snapshot>\n");
			xml.append("    <lastUpdated>").append(LAST_UPDATED.format(lastUpdated)).append("</lastUpdated>\n");
		} else {
			SnapshotFile latest = files.stream().max(Comparator.comparingInt(SnapshotFile::buildNumber).thenComparing(SnapshotFile::timestamp)).orElseThrow();
			xml.append("    <snapshot>\n");
			xml.append("      <timestamp>").append(latest.timestamp()).append("</timestamp>\n");
			xml.append("      <buildNumber>").append(latest.buildNumber()).append("</buildNumber>\n");
			xml.append("    </snapshot>\n");
			xml.append("    <lastUpdated>").append(LAST_UPDATED.format(lastUpdated)).append("</lastUpdated>\n");
			
			Map<String, SnapshotFile> newest = new TreeMap<>();
			for (SnapshotFile file : files) {
				String key = Objects.requireNonNullElse(file.classifier(), "") + ":" + file.extension();
				SnapshotFile current = newest.get(key);
				if (current == null || file.buildNumber() > current.buildNumber()) {
					newest.put(key, file);
				}
			}
			xml.append("    <snapshotVersions>\n");
			for (SnapshotFile file : newest.values()) {
				xml.append("      <snapshotVersion>\n");
				if (file.classifier() != null) {
					xml.append("        <classifier>").append(escapeXml(file.classifier())).append("</classifier>\n");
				}
				xml.append("        <extension>").append(escapeXml(file.extension())).append("</extension>\n");
				xml.append("        <value>").append(escapeXml(baseVersion + "-" + file.timestamp() + "-" + file.buildNumber())).append("</value>\n");
				xml.append("        <updated>").append(LAST_UPDATED.format(file.file().createdAt())).append("</updated>\n");
				xml.append("      </snapshotVersion>\n");
			}
			xml.append("    </snapshotVersions>\n");
		}
		xml.append("  </versioning>\n</metadata>\n");
		return xml.toString();
	}
	
	/**
	 * Resolves a non-unique snapshot file name (e.g. {@code toolkit-1.1.0-SNAPSHOT.jar}) to the latest timestamped snapshot.<br>
	 */
	@Nullable
	private FileEntity resolveNonUniqueSnapshot(@NonNull RepositoryEntity repository, @NonNull String path) throws Exception {
		Coordinates coordinates = parseCoordinates(path);
		if (coordinates == null || !coordinates.isSnapshot() || !coordinates.fileName().startsWith(coordinates.artifactId() + "-" + coordinates.version())) {
			return null;
		}
		String rest = coordinates.fileName().substring((coordinates.artifactId() + "-" + coordinates.version()).length());
		String classifier = null;
		String extension;
		if (rest.startsWith("-")) {
			int dot = rest.indexOf('.');
			if (dot < 0) {
				return null;
			}
			classifier = rest.substring(1, dot);
			extension = rest.substring(dot + 1);
		} else if (rest.startsWith(".")) {
			extension = rest.substring(1);
		} else {
			return null;
		}
		
		String directory = path.substring(0, path.lastIndexOf('/'));
		String baseVersion = coordinates.version().substring(0, coordinates.version().length() - "-SNAPSHOT".length());
		String finalClassifier = classifier;
		return this.snapshotFiles(repository, directory, coordinates.artifactId(), baseVersion).stream()
			.filter(file -> Objects.equals(file.classifier(), finalClassifier) && file.extension().equals(extension))
			.max(Comparator.comparingInt(SnapshotFile::buildNumber))
			.map(SnapshotFile::file)
			.orElse(null);
	}
	
	@Override
	protected boolean isMutable(@NonNull String path) {
		Coordinates coordinates = parseCoordinates(path);
		return coordinates != null && coordinates.isSnapshot();
	}
	
	@Override
	@NonNull
	protected String conflictMessage(@NonNull String path) {
		Coordinates coordinates = parseCoordinates(path);
		if (coordinates == null) {
			return super.conflictMessage(path);
		}
		return "Version " + coordinates.version() + " already exists; releases are immutable";
	}
	
	@Override
	protected void store(@NonNull Context ctx, @NonNull RepositoryEntity repository, @NonNull String path, @NonNull StoredBlob blob, @Nullable String username, boolean immutable) throws Exception {
		Coordinates coordinates = parseCoordinates(path);
		if (coordinates == null) {
			super.store(ctx, repository, path, blob, username, immutable);
			return;
		}
		
		ObjectNode metadata = Json.object();
		metadata.put("groupId", coordinates.groupId());
		metadata.put("artifactId", coordinates.artifactId());
		String fileMetadata = coordinates.fileName().endsWith(".jar") ? this.pluginDescriptor(blob) : null;
		// Clients upload the files of a version in parallel, the version is created by whichever upload comes first
		this.services.artifacts().transaction(work -> {
			if (this.alreadyStored(work, repository, path, blob, immutable)) {
				return false;
			}
			this.record(work, repository, path, blob, contentType(path), coordinates.packageName(), coordinates.version(), fileMetadata, username, immutable);
			return this.services.packages().ensure(work, repository.name(), coordinates.packageName(), coordinates.version(), Json.write(metadata), username);
		});
	}
	
	/**
	 * Reads the goal prefix and name of a Maven plugin from the descriptor in its jar, they are needed for the plugin list of the group metadata.<br>
	 *
	 * @return The file metadata as json, null if the jar is not a Maven plugin
	 */
	@Nullable
	private String pluginDescriptor(@NonNull StoredBlob blob) {
		try (ZipFile zip = new ZipFile(this.services.artifacts().blobStore().path(blob.sha256()).toFile())) {
			ZipEntry entry = zip.getEntry(PLUGIN_DESCRIPTOR);
			if (entry == null) {
				return null;
			}
			byte[] data;
			try (InputStream input = zip.getInputStream(entry)) {
				data = input.readNBytes(MAX_REMOTE_METADATA_SIZE + 1);
			}
			if (data.length > MAX_REMOTE_METADATA_SIZE) {
				return null;
			}
			Element root = MavenMetadata.parse(data).getDocumentElement();
			String prefix = MavenMetadata.childText(root, "goalPrefix");
			if (prefix == null) {
				return null;
			}
			ObjectNode metadata = Json.object();
			metadata.put("goalPrefix", prefix);
			String name = MavenMetadata.childText(root, "name");
			if (name != null) {
				metadata.put("pluginName", name);
			}
			return Json.write(metadata);
		} catch (Exception e) {
			// Not a readable jar or descriptor, the artifact is stored without plugin information
			return null;
		}
	}
	
	@Override
	protected void afterDelete(@NonNull UnitOfWork work, @NonNull RepositoryEntity repository, @NonNull List<FileEntity> deleted) throws SqlException {
		Set<List<String>> versions = new HashSet<>();
		for (FileEntity file : deleted) {
			if (file.packageName() != null && file.version() != null) {
				versions.add(List.of(file.packageName(), file.version()));
			}
		}
		for (List<String> version : versions) {
			if (this.services.artifacts().listByVersion(work, repository.name(), version.get(0), version.get(1)).isEmpty()) {
				this.services.packages().delete(work, repository.name(), version.get(0), version.get(1));
			}
		}
	}
	
	/**
	 * Coordinates of an artifact file within the Maven 2 layout.<br>
	 */
	public record Coordinates(@NonNull String groupId, @NonNull String artifactId, @NonNull String version, @NonNull String fileName) {
		
		@NonNull
		public String packageName() {
			return this.groupId + ":" + this.artifactId;
		}
		
		public boolean isSnapshot() {
			return this.version.endsWith("-SNAPSHOT");
		}
	}
	
	private record SnapshotFile(@NonNull String timestamp, int buildNumber, @Nullable String classifier, @NonNull String extension, @NonNull FileEntity file) {}
}
